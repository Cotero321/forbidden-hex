package com.example.akaishi.forbidden.magic.visual;

/**
 * 法术的<b>几何原型</b>（视觉层的"零件目录"·设计记忆 §7「先图后码」/ §19.5）。
 *
 * <p><b>为什么是"原型"而不是"每条 E 一种形状"</b>：20 条 E 的形态意象各不相同，
 * 但它们的<b>几何构成</b>其实反复用到同一小撮零件 —— 环、尖刺、壳、雾、涡、弧……
 * 把零件抽出来、让每条 E 用<b>不同的零件 + 不同的参数</b>组合，
 * 才能既有"每条 E 都不像"的多元性，又不必写 20 份互不相干的绘制代码。
 *
 * <p>参数（层数 / 自转 / 脉动 / 张缩 / 强调件数 / 内外翻转）由
 * {@link SpellVisualSpecs.Form} 逐条 E 给出 —— 同一原型在不同 E 上也会长得不一样。
 *
 * <p><b>零新增贴图</b>：全部原型都用顶点色 + 原版白色贴图画出来，
 * 颜色来自源与墨（见 {@link SpellVisualSpecs.Source} 与墨表的 {@code rgb()}）。
 */
public enum SpellGeometryKind {

    /** 光晕盘：一团由中心向外淡出的圆盘（最基础的能量体） */
    GLOW_DISC,

    /** 环：同心圆环，可正反自转（开合 / 封印 / 场域） */
    RING,

    /** 尖刺：从中心放射的锐角（冲击 / 穿刺） */
    SPIKE,

    /** 壳体：低面数多面体壳（护盾 / 承载） */
    SHELL,

    /** 雾：大而低透明度的缓慢涌动（隐匿） */
    MIST,

    /** 涡：带旋臂的螺旋（心智 / 聚拢） */
    VORTEX,

    /** 弧：一段横向电弧（斩断 / 连接） */
    ARC,

    /** 柱：沿某一轴的拉伸光柱（增幅 / 推送） */
    PILLAR,

    /** 符号环：一圈等分的标记点（召唤 / 削弱） */
    SIGIL,

    /** 碎片：向外飞散的三角片（破防） */
    SHARD,

    /** 链节：沿一条线排布的环扣（禁锢） */
    CHAIN,

    /** 涟漪：自中心向外扩散的多重圆环（闪现 / 感知 / 时序） */
    RIPPLE
}
