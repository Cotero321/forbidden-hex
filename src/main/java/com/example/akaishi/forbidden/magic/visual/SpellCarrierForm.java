package com.example.akaishi.forbidden.magic.visual;

/**
 * 法术的<b>载体形态</b>（视觉层的"骨架"·设计记忆 §19.3 / §36.2）。
 *
 * <p>载体由交付方式 X 决定 —— 它回答的是"这段效果<b>画在哪儿、怎么存在</b>"：
 * 一条束？一个飞行的核心？挂在目标身上？铺在地上？还是延迟再亮一次？
 *
 * <p>与 {@link SpellGeometryKind}（画<b>什么</b>）正交：
 * 同一个"环"可以是地上法阵的一部分、也可以是飞行核心周围的一圈 ——
 * 差别全在载体。这正是 §19.1 拆开的那两件事在视觉层上的对应。
 */
public enum SpellCarrierForm {

    /** 束：从施法者沿一条线到命中点（X1 直射 / X3 引导） */
    BEAM,

    /** 核心：一枚自持的飞行物（X2 投射） */
    ORB,

    /** 印记：挂在目标身上（X4 附着） */
    MARK,

    /** 场：铺在落点上、按秒重放（X5 布场） */
    FIELD,

    /** 残影：原地延迟亮起的一次（X6 回响） */
    AFTERIMAGE,

    /** 齐射：多枚沿同一方向错开（X7 连发） */
    SALVO
}
