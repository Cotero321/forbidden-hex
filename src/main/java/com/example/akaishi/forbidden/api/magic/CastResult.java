package com.example.akaishi.forbidden.api.magic;

/**
 * 施法请求的结果码（设计记忆 §11 + §21.1 + §24.1）。
 *
 * <p>只有 {@link #SUCCESS} 表示"已受理并完成结算"；其余全部表示<b>拒绝</b>，
 * 且<b>一律不扣费、不冷却</b>（拒绝发生在扣费之前）。
 */
public enum CastResult {

    /** 受理并完成结算（扣费、进冷却；实际效果由执行层产生） */
    SUCCESS,

    /** 句子不成立：空句 / 含未知词 / 某段超过 2 词 / 整句无核心词（§7「不存在」） */
    NOT_EXISTS,

    /** 语义自相矛盾：对立词轴 / 同词重复 / 墨对立轴 / 星墨独占被破坏（§7「冲突」） */
    CONFLICT,

    /** 句内含<b>尚未解锁</b>的词（§7「不存在」的子类，单列以便界面提示"去学这个词"） */
    NOT_UNLOCKED,

    /** 词数超过当前等级允许的上限（§10：1 / 2 / 3 / 5 / 7 / 8） */
    WORD_LIMIT_EXCEEDED,

    /** 三池或理智值不足（§21.6：<b>不允许透支</b>；SAN 也归到本码） */
    POOL_INSUFFICIENT,

    /** 仍在冷却中（§21.1） */
    COOLDOWN,

    /** 已有一次施法进行中（§21.1 单施法槽：拒绝，不排队） */
    BUSY,

    /** 处于过载罚站（§24.1） */
    OVERLOADED,

    /** 星墨在非灰源（SAN）下无法生效（§3.1） */
    STAR_SOURCE_INVALID,

    /**
     * 魔法服务未安装（禁忌模块缺席）。
     *
     * <p>本码是 §11 表之外<b>新增</b>的：§11 只列了"成功 / 未解锁 / 冲突 / 不存在 / 池不足 / 冷却 / 星墨非法源"，
     * 但门面在模块缺席时返回兜底实现（见 {@code MagicServices}），那条路径需要一个诚实的码 ——
     * 用 {@link #NOT_EXISTS} 会把"没有这个系统"说成"你的句子不成立"，误导排查。
     */
    SERVICE_UNAVAILABLE
}
