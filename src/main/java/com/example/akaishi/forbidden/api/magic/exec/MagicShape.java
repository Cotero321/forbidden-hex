package com.example.akaishi.forbidden.api.magic.exec;

/**
 * 作用形状 G —— 目标解析器<b>按形状分工</b>的键（设计记忆 §19.2 / §8.7 / §36.1）。
 *
 * <p>为什么形状单独成枚举而不是塞进 E 或 X：{@link ITargetResolver} 只该关心"怎么圈人"，
 * 与"做什么"（E）和"怎么送"（X）正交。把它们混在一格里，就是 §19.1 说的"焊死"。
 */
public enum MagicShape {

    /** 自身（施法者即目标，如自增益 / 自传送） */
    SELF,

    /** 单体（视线内的一个目标；靠 {@code 叉} 递增目标数） */
    SINGLE,

    /** 射线（沿视线方向打一条线，命中首个遮挡物或目标） */
    RAY,

    /** 锥形（以视线为轴的扇形，覆盖多个目标） */
    CONE,

    /** 球形（以原点为中心的球，覆盖多个目标） */
    SPHERE,

    /** 链跳（命中后向邻近目标跳跃，跳数由规模修正与 {@code 叉} 给） */
    CHAIN,

    /** 区域（布场落点：先落点、后持续生效） */
    AREA
}
